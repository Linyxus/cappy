"""Aggregate pyperf JSON (and optionally a JMH `-rf json` file) into
``notes/benchmark.md`` plus ``results.jsonl``.

pyperf benchmark names registered by ``run_bench.py`` follow the shape
``<BenchClass>.<op>@<size>`` (e.g. ``HashMapBench.access@4096``). The
matching JMH benchmark id is
``dotty.tools.benchmarks.<package>.<BenchClass>.<op>`` plus a
``params.size`` field; the package — ``immutable`` or ``mutable`` — is
recovered from the JMH benchmark id, and is what we use to build the
shared ``bench`` key (``"immutable.HashMapBench"`` etc.).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import pyperf


PY_NAME_RE = re.compile(r"^(?P<pkg>immutable|mutable)\.(?P<bench>[A-Za-z]+Bench)\.(?P<op>[a-z]+)@(?P<size>\d+)$")
JMH_NAME_RE = re.compile(r"^dotty\.tools\.benchmarks\.(?P<pkg>immutable|mutable)\.(?P<bench>[A-Za-z]+Bench)\.(?P<op>[a-z]+)$")


def _load_pyperf(path: Path) -> dict[tuple[str, str, str, int], tuple[float, float]]:
    """key=(pkg, short_bench, op, size); value=(ops_per_sec, ops_per_sec_stdev)."""
    suite = pyperf.BenchmarkSuite.load(str(path))
    out: dict[tuple[str, str, str, int], tuple[float, float]] = {}
    for bench in suite:
        m = PY_NAME_RE.match(bench.get_name())
        if m is None:
            print(f"warn: skipping unparseable pyperf name {bench.get_name()!r}", file=sys.stderr)
            continue
        mean = bench.mean()           # seconds per op
        stdev = bench.stdev() if bench.get_nvalue() > 1 else 0.0
        ops_per_sec = 1.0 / mean
        # Convert stdev(latency) to stdev(throughput): 1st-order propagation.
        ops_per_sec_err = (stdev / (mean * mean)) if stdev else 0.0
        out[(m["pkg"], m["bench"], m["op"], int(m["size"]))] = (ops_per_sec, ops_per_sec_err)
    return out


def _load_jmh(path: Path) -> dict[tuple[str, str, str, int], tuple[float, float]]:
    """key=(pkg, short_bench, op, size); value=(ops_per_sec, score_error)."""
    raw = json.loads(path.read_text())
    out: dict[tuple[str, str, str, int], tuple[float, float]] = {}
    for entry in raw:
        m = JMH_NAME_RE.match(entry["benchmark"])
        if m is None:
            print(f"warn: skipping unparseable JMH name {entry['benchmark']!r}", file=sys.stderr)
            continue
        size = int(entry.get("params", {}).get("size", 0))
        primary = entry.get("primaryMetric", {})
        score = float(primary.get("score", 0.0))
        err = float(primary.get("scoreError", 0.0))
        out[(m["pkg"], m["bench"], m["op"], size)] = (score, err)
    return out


def _emit_jsonl(rows: list[dict], path: Path) -> None:
    with path.open("w") as f:
        for row in rows:
            f.write(json.dumps(row))
            f.write("\n")


def _emit_md(rows: list[dict], path: Path) -> None:
    """Markdown table that mirrors notes/benchmark.md: one row per
    (bench, op) at the largest size present in the data."""
    by_bench_op: dict[tuple[str, str], dict] = {}
    for row in rows:
        key = (row["bench"], row["op"])
        if key not in by_bench_op or row["size"] > by_bench_op[key]["size"]:
            by_bench_op[key] = row
    sorted_rows = sorted(by_bench_op.values(), key=lambda r: (r["bench"], r["op"]))

    def fmt(x: float | None) -> str:
        if x is None: return "—"
        return f"{x:,.2f}"

    lines = [
        "# Benchmark Results",
        "",
        "JVM vs Python backend, taking the maximal size for each `bench.op`.",
        "Generated by `stdlib-bench-py/python-shim/results_to_md.py`.",
        "",
        "| benchmark | Java op/s | Python op/s | Java/Python |",
        "| --- | ---: | ---: | ---: |",
    ]
    for row in sorted_rows:
        label = f"{row['bench']}.{row['op']}"
        jvm = row.get("jvm_score_ops_per_sec")
        py = row["py_score_ops_per_sec"]
        ratio = row.get("jvm_over_py")
        lines.append(f"| {label} | {fmt(jvm)} | {fmt(py)} | {fmt(ratio)} |")
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--pyperf-json", required=True, type=Path)
    parser.add_argument("--jmh-json", type=Path, default=None)
    parser.add_argument("--out-md", required=True, type=Path)
    parser.add_argument("--out-jsonl", required=True, type=Path)
    args = parser.parse_args()

    py = _load_pyperf(args.pyperf_json)
    jmh = _load_jmh(args.jmh_json) if args.jmh_json else {}

    rows: list[dict] = []
    for (pkg, short_bench, op, size), (py_score, py_err) in sorted(py.items()):
        bench_id = f"{pkg}.{short_bench}"
        jvm_score, jvm_err = jmh.get((pkg, short_bench, op, size), (None, None))
        ratio = (jvm_score / py_score) if (jvm_score is not None and py_score) else None
        rows.append({
            "benchmark":             f"{bench_id}.{op}",
            "bench":                 bench_id,
            "op":                    op,
            "size":                  size,
            "jvm_score_ops_per_sec": jvm_score,
            "jvm_error_ops_per_sec": jvm_err,
            "py_score_ops_per_sec":  py_score,
            "py_error_ops_per_sec":  py_err,
            "jvm_over_py":           ratio,
        })

    _emit_jsonl(rows, args.out_jsonl)
    _emit_md(rows, args.out_md)
    print(f"wrote {len(rows)} rows to {args.out_jsonl} and {args.out_md}")


if __name__ == "__main__":
    main()
